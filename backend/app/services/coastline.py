def _flat_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Distance approchée en km, suffisante à l'échelle de l'île."""
    return math.hypot((lat2 - lat1) * KM_PER_DEG, (lon2 - lon1) * KM_PER_DEG * _COS_LAT)


def zone_of_index(index: int) -> int:
    """Rang de la façade qui contient le point d'index donné de COAST_RING."""
    for rank, start in enumerate(ZONE_STARTS):
        end = ZONE_STARTS[(rank + 1) % len(ZONE_STARTS)]
        inside = start <= index < end if start < end else index >= start or index < end
        if inside:
            return rank
    return 0


